    for (final (q, qmax, unit, food, note, original, scale, system, want) in displayCases) {
      final ing = Ingredient(quantity: q, quantityMax: qmax, unit: unit, food: food, note: note, original: original);
      expect(ingredientDisplay(ing, scale, system), want, reason: '$original x$scale ${system.name}');
      if (scale != 1 || system != UnitSystem.original) {
        expect(displayIngredient(ing, factor: scale, system: system).toString(), want);
      }
    }
  });

  test('convert + round_metric match Rust', () {
    for (final (q, unit, system, wantQ, wantUnit, wantRounded) in convertCases) {
      final got = convert(q, unit, system);
      final why = '$q $unit ${system.name}';
      if (wantQ == null) {
        expect(got, isNull, reason: why);
        continue;
      }
      expect(got, isNotNull, reason: why);
      expect(got!.$2, wantUnit, reason: why);
      expect(got.$1, closeTo(wantQ, 1e-9), reason: why);
      expect(roundMetric(got.$1, got.$2), closeTo(wantRounded!, 1e-9), reason: why);
    }
    expect(convert(1, 'cup', UnitSystem.original), isNull);
  });

  test('Rust unit tests: conversions', () {
    var (q, u) = convert(2, 'cup', UnitSystem.metric)!;
    expect(u, 'ml');
    expect(q, closeTo(473.176, 0.01));
    (q, u) = convert(500, 'g', UnitSystem.imperial)!;
    expect(u, 'lb');
    expect(q, closeTo(1.102, 0.01));
    expect(convert(10, 'ml', UnitSystem.imperial)!.$2, 'tsp');
    expect(convert(1, 'cup', UnitSystem.imperial), isNull);
    expect(convert(1, 'clove', UnitSystem.metric), isNull);
    expect(convertBetween(1, 'lb', 'oz'), closeTo(16, 0.01));
    expect(convertBetween(1, 'lb', 'cup'), isNull);
    expect(convertBetween(2, 'clove', 'clove'), 2);
    expect(convertBetween(1, 'clove', 'pinch'), isNull);
    expect(convertBetween(1, 'l', 'dl'), closeTo(10, 1e-9));
  });

  test('canonical units, aliases and case-sensitive aliases', () {
    const cases = {
      'Tablespoons': 'tbsp',
      'T': 'tbsp',
      't': 'tsp',
      'Tb': 'tbsp',
      'TB': null,
      'lbs.': 'lb',
      'L': 'l',
      'l': 'l',
      'whatever': null,
      'cc': 'ml',
      'cc.': 'ml',
      'CC': 'ml',
      'mL': 'ml',
      'ML': 'ml',
      'c. à c.': 'tsp',
      'C. À S.': 'tbsp',
      'Cups': 'cup',
      'C': 'cup',
      'fl. oz': 'fl oz',
      'fl.oz.': 'fl oz',
      'oz.': 'oz',
      'oz..': 'oz',
      '  grams  ': 'g',
      'el': 'tbsp',
      'EL': 'tbsp',
      'tasse': 'cup',
      'dl': 'dl',
      'cl': 'cl',
      'mg': 'mg',
      'Kilos': 'kg',
      'pn': 'pinch',
      'tins': 'can',
      'handful': 'handful',
      'pc': 'piece',
    };
    cases.forEach((input, want) => expect(canonicalUnit(input), want, reason: input));
    expect(dimensionOf('ml'), Dimension.volume);
    expect(dimensionOf('oz'), Dimension.mass);
    expect(dimensionOf('clove'), Dimension.count);
    expect(dimensionOf('whatever'), isNull);
  });

  test('alias table matches Rust (order included)', () {
    expect(aliasTable(), rustAliasTable);
  });

  test('format_quantity (fractions with 0.02 tolerance)', () {
    const cases = <(double, String, String)>[
      (1.5, '1 1/2', '1½'),
      (0.333, '1/3', '⅓'),
      (2.0, '2', '2'),
      (0.1, '0.1', '0.1'),
      (1.999, '2', '2'),
      (250.0, '250', '250'),
      (0.125, '1/8', '⅛'),
      (0.98, '1', '1'),
      (0.97, '0.97', '0.97'),
      (0.03, '0.03', '0.03'),
      (0.029, '0', '0'),
      (1.31, '1.31', '1.31'),
      (1.32, '1 1/3', '1⅓'),
      (1.35, '1 1/3', '1⅓'),
      (2.6667, '2 2/3', '2⅔'),
      (19.99, '20', '20'),
      (20.04, '20', '20'),
      (20.05, '20.1', '20.1'),
      (123.456, '123.5', '123.5'),
      (0.66, '2/3', '⅔'),
      (0.5, '1/2', '½'),
      (7 / 3, '2 1/3', '2⅓'),
      (0.0, '0', '0'),
      (1 / 16, '0.06', '0.06'),
      (3.14159, '3 1/8', '3⅛'),
      (0.75, '3/4', '¾'),
      (0.7699, '3/4', '¾'),
      (0.7701, '0.77', '0.77'),
      (12.345, '12 1/3', '12⅓'),
      (-1.5, '-1', '-1'),
    ];
    for (final (q, ascii, unicode) in cases) {
      expect(formatQuantity(q), ascii, reason: '$q');
      expect(formatQuantityUnicode(q), unicode, reason: '$q');
    }
    expect(formatQuantity(double.nan), '');
  });

  test('unit labels pluralise like Rust', () {
    expect(unitLabel('cup', 1.0), 'cup');
    expect(unitLabel('cup', 1.0000000001), 'cup');
    expect(unitLabel('cup', 1.01), 'cups');
    expect(unitLabel('cup'), 'cup');
    expect(unitLabel('pinch', 2), 'pinches');
    expect(unitLabel('bunch', 3), 'bunches');
    expect(unitLabel('handful', 2), 'handfuls');
    expect(unitLabel('g', 5), 'g');
    expect(unitLabel('weird', 2), 'weird');
  });

  test('unicode fractions like the cookbook', () {
    expect(unicodeFractions('1 1/2 cups'), '1½ cups');
    expect(unicodeFractions('1/4–1/2 tsp'), '¼–½ tsp');
    expect(unicodeFractions('3 1/2–5 1/4 cloves'), '3½–5¼ cloves');
    expect(unicodeFractions('11/2 cups'), '11/2 cups');
  });

  test('unit system parsing', () {
    expect(UnitSystem.parse('Metric'), UnitSystem.metric);
    expect(UnitSystem.parse('us'), UnitSystem.imperial);
    expect(UnitSystem.parse(null), UnitSystem.original);
  });
}
